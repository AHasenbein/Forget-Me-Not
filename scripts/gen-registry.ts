import { existsSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { FEATURES_DIR, listFeatureDirs } from '../core/feature-registry/discover';

// Generates two gitignored static registries for Metro (it cannot scan the filesystem at runtime):
//  - registry.generated.ts      manifests (nav, flags, metadata)
//  - ui-registry.generated.ts   features/<name>/ui/index.tsx (dashboard widgets), kept separate so the
//                               server never has to load React Native code
const names = listFeatureDirs();
const out = (f: string) => fileURLToPath(new URL(`../core/feature-registry/${f}`, import.meta.url));

writeFileSync(
  out('registry.generated.ts'),
  `// GENERATED by scripts/gen-registry.ts. Do not edit or commit.
import type { FeatureManifest } from './manifest';
${names.map((n, i) => `import m${i} from '@features/${n}/manifest';`).join('\n')}

export const manifests: FeatureManifest[] = [${names.map((_, i) => `m${i}`).join(', ')}];
`,
);

const withUi = names.filter((n) =>
  ['index.tsx', 'index.ts'].some((f) => existsSync(join(FEATURES_DIR, n, 'ui', f))),
);
writeFileSync(
  out('ui-registry.generated.ts'),
  `// GENERATED by scripts/gen-registry.ts. Do not edit or commit.
import type { FeatureUi } from './ui';
${withUi.map((n, i) => `import u${i} from '@features/${n}/ui';`).join('\n')}

export const uis: Record<string, FeatureUi> = {${withUi.map((n, i) => ` '${n}': u${i}`).join(',')} };
`,
);
console.log(`registry: ${names.length} feature(s), ${withUi.length} with UI`);
