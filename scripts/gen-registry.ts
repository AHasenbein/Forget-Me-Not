import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { listFeatureDirs } from '../core/feature-registry/discover';

// Generates a gitignored static registry for Metro (it cannot scan the filesystem at runtime).
const names = listFeatureDirs();
const body = `// GENERATED by scripts/gen-registry.ts. Do not edit or commit.
import type { FeatureManifest } from './manifest';
${names.map((n, i) => `import m${i} from '@features/${n}/manifest';`).join('\n')}

export const manifests: FeatureManifest[] = [${names.map((_, i) => `m${i}`).join(', ')}];
`;
writeFileSync(
  fileURLToPath(new URL('../core/feature-registry/registry.generated.ts', import.meta.url)),
  body,
);
console.log(`registry: ${names.length} feature(s)`);
