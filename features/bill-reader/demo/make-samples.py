"""One-off generator for the FICTIONAL demo bills (features/bill-reader/demo/samples.ts). Not part of any npm script.
Every company, name, account number and address here is made up. Run: python3 features/bill-reader/demo/make-samples.py"""
import base64, json, os
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
REG = "/System/Library/Fonts/Supplemental/Arial.ttf"
BOLD = "/System/Library/Fonts/Supplemental/Arial Bold.ttf"
f = lambda p, s: ImageFont.truetype(p, s)
W, H = 800, 1040

def bill(name, color, company, tagline, title, lines, amount, due, footer, scam=False):
    im = Image.new("RGB", (W, H), "white")
    d = ImageDraw.Draw(im)
    d.rectangle([0, 0, W, 150], fill=color)
    d.text((40, 38), company, font=f(BOLD, 46), fill="white")
    d.text((40, 100), tagline, font=f(REG, 24), fill="white")
    d.text((40, 190), title, font=f(BOLD, 40), fill="black")
    y = 270
    for k, v in lines:
        d.text((40, y), k, font=f(REG, 28), fill=(90, 90, 90))
        d.text((360, y), v, font=f(BOLD, 28), fill="black")
        y += 52
    y += 20
    d.rectangle([40, y, W - 40, y + 190], outline=(220, 30, 30) if scam else color, width=5)
    d.text((70, y + 22), "TOTAL AMOUNT DUE", font=f(BOLD, 28), fill="black")
    d.text((70, y + 70), amount, font=f(BOLD, 72), fill=(200, 0, 0) if scam else "black")
    d.text((W - 330, y + 22), "PAY BY", font=f(BOLD, 28), fill="black")
    d.text((W - 330, y + 70), due, font=f(BOLD, 40), fill="black")
    y += 230
    for line in footer:
        d.text((40, y), line, font=f(BOLD if scam else REG, 30 if scam else 26), fill=(200, 0, 0) if scam else (70, 70, 70))
        y += 44
    return im

samples = [
    ("water", "Water bill", bill("water", (20, 110, 170), "Fictional Water Co", "Clean water for Example Town", "Water bill",
        [("Account", "0000-111-222"), ("Customer", "Margaret Example"), ("Service address", "1 Sample Street"), ("Billing period", "Sep 20 - Oct 19"), ("Water used", "4,200 gallons")],
        "$31.50", "Nov 20, 2026", ["Pay online, by mail, or at any branch.", "Questions? See the back of this bill."])),
    ("electric", "Electric bill", bill("electric", (210, 140, 20), "Sunrise Electric", "Power for Example County", "Electric bill",
        [("Account", "0000-333-444"), ("Customer", "Margaret Example"), ("Service address", "1 Sample Street"), ("Billing period", "Sep 25 - Oct 24"), ("Electricity used", "612 kWh")],
        "$84.12", "Nov 12, 2026", ["Pay online, by mail, or by the automatic draft.", "Questions? See the back of this bill."])),
    ("internet", "Internet bill", bill("internet", (90, 50, 160), "BrightNet Internet", "Fast home internet", "Internet bill",
        [("Account", "0000-555-666"), ("Customer", "Margaret Example"), ("Plan", "Home 100"), ("Billing period", "Oct 1 - Oct 31"), ("Plan price", "$59.99 / month")],
        "$59.99", "Nov 28, 2026", ["Pay online or by mail.", "Questions? See the back of this bill."])),
    ("scam", "Scary letter", bill("scam", (130, 0, 0), "County Revenue Office", "OFFICIAL NOTICE", "FINAL NOTICE",
        [("Case number", "000-FAKE-0000"), ("Name", "Margaret Example"), ("Reason", "Unpaid account")],
        "$499.00", "TODAY", ["PAY TODAY WITH GIFT CARDS", "or you will be ARRESTED.", "Call 555-0100 now to pay.", "Do not tell anyone."], scam=True)),
]
out = []
for sid, label, im in samples:
    path = os.path.join(HERE, f"{sid}.jpg")
    im.save(path, "JPEG", quality=80, optimize=True)
    b64 = base64.b64encode(open(path, "rb").read()).decode()
    out.append({"id": sid, "label": label, "mediaType": "image/jpeg", "data": b64})
    os.remove(path)
ts = "// GENERATED by make-samples.py. Fictional demo bills (no real company, person or number). Do not edit by hand.\n"
ts += "export interface SampleBill {\n  id: string;\n  label: string;\n  mediaType: 'image/jpeg';\n  data: string; // base64\n}\n\n"
ts += "export const SAMPLE_BILLS: readonly SampleBill[] = " + json.dumps(out, indent=2) + " as const;\n"
open(os.path.join(HERE, "samples.ts"), "w").write(ts)
print({s["id"]: len(s["data"]) for s in out})
